// The lognormal in the mean m and the variance v of Y. With C = log(y/m)
// and S = log(1 + v/m^2), log y - mu_l = C + S/2 and the log-density is
//   -log y - log(2 pi)/2 - log(S)/2 - (C + S/2)^2 / (2 S).
// Every component below is a closed form derived offline with sympy
// (stabilita/gen_lognormal2.py), one exported function per order and per
// surface; y enters through C, the variance only through S. Each is
// checked numerically against independent references in the tests.


// order 1 of log f in (mean, var)
// [[Rcpp::export]]
List lognormal2_gradient_cpp(NumericVector y, NumericVector mean, NumericVector var) {
  const int n = y.size();
  const int n_mean = mean.size(), n_var = var.size();
  NumericVector o_mean(n);
  NumericVector o_var(n);
  double m = 0.0, v = 0.0, S = 0.0;
  double t0 = 0.0;
  double t1 = 0.0;
  double t2 = 0.0;
  double t3 = 0.0;
  double t4 = 0.0;
  double t6 = 0.0;
  auto set_params = [&](int i) {
    m = mean[i % n_mean]; v = var[i % n_var];
    S = std::log1p(v / (m * m));
    t0 = 1.0/m;
    t1 = 1.0/S;
    t2 = t0*t1;
    t3 = 1.0/(std::pow(m, 2) + v);
    t4 = m*t3;
    t6 = std::pow(S, -2);
  };
  const bool scalar = n_mean == 1 && n_var == 1;
  if (scalar) set_params(0);
  for (int i = 0; i < n; i++) {
    if (!scalar) set_params(i);
    const double yy = y[i];
    const double C = std::log(yy / m);
    o_mean[i] = d7::lognormal2_score_mean(m, v, S, C);
    o_var[i] = d7::lognormal2_score_var(m, v, S, C);
  }
  (void) S;
  return List::create(Named("mean") = o_mean, Named("var") = o_var);
}

// order 2 of log f in (mean, var)
// [[Rcpp::export]]
List lognormal2_hessian_cpp(NumericVector y, NumericVector mean, NumericVector var) {
  const int n = y.size();
  const int n_mean = mean.size(), n_var = var.size();
  NumericVector o_mean_mean(n);
  NumericVector o_var_var(n);
  NumericVector o_mean_var(n);
  double m = 0.0, v = 0.0, S = 0.0;
  double t0 = 0.0;
  double t1 = 0.0;
  double t2 = 0.0;
  double t3 = 0.0;
  double t4 = 0.0;
  double t6 = 0.0;
  double t9 = 0.0;
  double t10 = 0.0;
  double t11 = 0.0;
  double t12 = 0.0;
  double t13 = 0.0;
  double t14 = 0.0;
  double t15 = 0.0;
  double t16 = 0.0;
  auto set_params = [&](int i) {
    m = mean[i % n_mean]; v = var[i % n_var];
    S = std::log1p(v / (m * m));
    t0 = std::pow(m, 2);
    t1 = 1.0/t0;
    t2 = std::pow(S, -2);
    t3 = 1.0/S;
    t4 = 1.0/(t0 + v);
    t6 = std::pow(S, -3);
    t9 = t2*t4;
    t10 = 4*t9;
    t11 = 2*t0;
    t12 = 1.0/(std::pow(m, 4) + t11*v + std::pow(v, 2));
    t13 = (1.0/2.0)*t2;
    t14 = 1.0/m;
    t15 = t14*t9;
    t16 = m*t12;
  };
  const bool scalar = n_mean == 1 && n_var == 1;
  if (scalar) set_params(0);
  for (int i = 0; i < n; i++) {
    if (!scalar) set_params(i);
    const double yy = y[i];
    const double C = std::log(yy / m);
    const double t5 = std::pow(C, 2);
    const double t7 = t5*t6;
    o_mean_mean[i] = d7::lognormal2_hess_mean_mean(m, v, S, C);
    o_var_var[i] = d7::lognormal2_hess_var_var(m, v, S, C);
    o_mean_var[i] = -C*t15 + m*t12*t2 + m*t12*t3 + (1.0/4.0)*m*t12 + 2*t14*t4*t5*t6 - t15 - t16*t2*t5 - 2*t16*t7;
  }
  (void) S;
  return List::create(Named("mean_mean") = o_mean_mean, Named("var_var") = o_var_var, Named("mean_var") = o_mean_var);
}

// order 2, expected: E[L] = mu_l, E[L^2] = mu_l^2 + S
// [[Rcpp::export]]
List lognormal2_expected_hessian_cpp(NumericVector y, NumericVector mean, NumericVector var) {
  const int n = y.size();
  const int n_mean = mean.size(), n_var = var.size();
  NumericVector o_mean_mean(n);
  NumericVector o_var_var(n);
  NumericVector o_mean_var(n);
  double m = 0.0, v = 0.0, S = 0.0;
  double t0 = 0.0;
  double t1 = 0.0;
  double t2 = 0.0;
  double t3 = 0.0;
  double t4 = 0.0;
  double t5 = 0.0;
  double t6 = 0.0;
  double t7 = 0.0;
  double t8 = 0.0;
  double t9 = 0.0;
  double t10 = 0.0;
  double t11 = 0.0;
  double t12 = 0.0;
  auto set_params = [&](int i) {
    m = mean[i % n_mean]; v = var[i % n_var];
    S = std::log1p(v / (m * m));
    t0 = std::pow(m, 2);
    t1 = 1.0/(t0 + v);
    t2 = 1.0/t0;
    t3 = 1.0/S;
    t4 = 2*t3;
    t5 = std::pow(v, 2);
    t6 = 1.0/(std::pow(m, 4) + 2*t0*v + t5);
    t7 = t6*v;
    t8 = t0*t6;
    t9 = t2*t5*t6;
    t10 = std::pow(S, -2);
    t11 = 1.0/m;
    t12 = t11*t3;
  };
  const bool scalar = n_mean == 1 && n_var == 1;
  if (scalar) set_params(0);
  for (int i = 0; i < n; i++) {
    if (!scalar) set_params(i);
    o_mean_mean[i] = d7::lognormal2_expected_mean_mean(m, v, S);
    o_var_var[i] = d7::lognormal2_expected_var_var(m, v, S);
    o_mean_var[i] = (1.0/2.0)*t1*t12 + t10*t11*t7 + (1.0/2.0)*t12*t7;
  }
  (void) S;
  return List::create(Named("mean_mean") = o_mean_mean, Named("var_var") = o_var_var, Named("mean_var") = o_mean_var);
}

