using namespace Rcpp;

static inline double gg1d_psi(double x, int n) { return R::psigamma(x, (double) n); }
static inline dd gg1d_psi(const dd& x, int n) { return n == 0 ? dd_B0(x) + dd_log(x) : dd_psi_n(x, n); }

