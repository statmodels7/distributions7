// The third and fourth derivatives of the expected information of the
// Poisson-inverse Gaussian, family pig1 (parameters mu, sigma), on the parameter scale.
//
// With S = E_sigma_sigma the whole expected Hessian follows from S,
//   E_mu_sigma = R1 S,   E_mu_mu = N + R2 S,
//   R1 = -sigma^2 / (1 + sigma mu),  R2 = sigma^4 / (1 + sigma mu)^2,  N = -1 / (mu (1 + sigma mu)).
// The identity comes from the map alpha = sqrt(1 + 2 sigma mu)/sigma to the orthogonal
// parametrization of pig2 (src/d34e_pig2.cpp), where E_mu_alpha = 0 and
// E_mu_mu = -1/mu + 1/sqrt(mu^2 + alpha^2), and sqrt(mu^2 + alpha^2) = (1 + sigma mu)/sigma. The
// derivatives of orders 3 and 4 of E_mu_mu and E_mu_sigma are Leibniz sums of the partials of S of orders
// 0 to K and the exact derivatives of R1, R2 and N (assemble3 and assemble4 of pt_pig1_d34e_map.h,
// generated by misure_d34e/agents/pig1map/gen_hdr.py), so that only S is a sum over the support.
// Composing the third and fourth derivatives of pig2's Eaa through the map was measured and
// rejected: the derivatives in sigma of alpha(mu, sigma) = sqrt(1 + 2 sigma mu)/sigma grow as
// sigma^-k, and the chain rule through them loses about log10(sigma^-4) digits where sigma is small.
//
// The partials of S of orders 0 to K in (mu, sigma) come from one of four sources.
//  - Where (1 + mu) sigma <= 0.04 (mu < 20), 0.08 (20 <= mu < 200) or 0.1 (mu >= 200), from the series
//    of S in sigma (the entry E1[('s', 's')] of stabilita/pig_asym_series_N20.py: coefficients
//    polynomial in mu, exact in double), differentiated term by term. Measured against 60- and
//    70-digit sums, the terms of order above 21 leave at most 1.4e-13 of the largest component of
//    order 4 at the cuts, and the evaluation in double is accurate to 1e-15.
//  - Where mu >= 1000 and sigma <= 0.003 (mu < 1e4), 0.01 (mu < 1e5) or 0.03 (mu >= 1e5), from the
//    expansion of S in 1/mu at a fixed x = sigma mu (pt_pig1_d34e_asym.h): seven terms mu^(2-d) F_d(x),
//    F_d rational in x with denominator (1 + x)^(3d+2), differentiated in closed form. It costs a fixed
//    number of operations and agrees with 70-digit sums to 1e-15 of the largest component (1e-14 at
//    the corner mu = 1000, sigma = 0.003, where the truncation is largest). The walk cannot reach 1e-10
//    there: at mu = 1e6 and (1 + mu) sigma = 0.3 it gives 7e-9 (order 3) and 1e-8 (order 4). Its rows
//    for the pure sigma derivatives of log f are sums of terms of size y mu that cancel to size mu, so
//    that the derivatives of log S_y in w from the recurrence PigSeqW, good to 2e-14, become a relative
//    error of 8e-9 in them (2e-10 if the derivatives in w were exact), and the polynomials that form
//    the partials of S cancel again.
//  - Where the first two do not apply, from the expansion of S in 1/mu at a fixed sigma
//    (pt_pig1_fixsig.h): S = sum_p mu^-p G_p(sigma), G_p a Laurent polynomial with 2p + 1 dyadic coefficients
//    (p <= 20), differentiated term by term. Terms are added until the last one is below 1e-14 of the largest
//    component of each order; the route declines where the terms start to grow before that or p = 20 is
//    reached, which happens for mu below about max(1e3, 1e4 sigma).
//  - Elsewhere from the walk over the support: S = E[l_ss] = -E[l_s l_s] and d_c E[h] = E[d_c h +
//    h l_c], so each partial is the expectation of a polynomial in the partials L{i}{j} of the log
//    mass, accumulated by AccS3 or AccS4 over the row of pt_pig_d34e.h with the stopping rule of
//    pig_expected_obs() in pig_hd.cpp (d34_walk).
//
// The components are in the order of d3expected_names() and d4expected_names(): the pairs
// (mu_mu, sigma_sigma, mu_sigma) in turn, and within a pair the index multisets with j indices on
// sigma, j = 0, 1, ...

#include <Rcpp.h>
#include <algorithm>
#include <cmath>
#include "d7_par.h"
#include "d34e_run.h"
#include "pt_pig_d34e.h"
#include "pt_pig1_d34e_map.h"
#include "pt_pig1_d34e_asym.h"
#include "pt_pig1_fixsig.h"
using namespace Rcpp;

namespace {

// The partials of S of orders 0..K at one (mu, sigma), in the layout s[k (k + 1) / 2 + q] (order k,
// q indices on sigma). The walk over the support runs only where the series in sigma, the expansion at fixed
// x and the expansion at fixed sigma (pt_pig1_fixsig.h) all decline. Returns false where the walk could not
// be completed.
template <int K>
static bool pig1_s_partials(const double m, const double x, double* s) {
    if (pig_map::series_region(m, x)) {
        pig_map::series_S(m, x, K, s);
        return true;
    }
    if (pig_map::asym_region(m, x)) {
        pig_map::asym_S(m, x, K, s);
        return true;
    }
    if (pig_map::fixsig_S(m, x, K, s)) return true;
    const double w = 0.5 * x / d7::sqrt_cr(1.0 + 2.0 * x * m);
    const double tail = 2.0 * x * m;
    auto row4 = [&](double yy, const double* pre, double* v) {
        d34e_pig::pig1_row(yy, m, x, 4, false, v, pre);
    };
    auto row5 = [&](double yy, double* v) {
        d34e_pig::pig1_d5_row(yy, m, x, v + 15);
    };
    if constexpr (K == 3) {
        return d34e_pig::d34_walk<3, d7::PigSeqW>(m, w, tail, row4, row5, pig_map::AccS3(), s);
    } else {
        return d34e_pig::d34_walk<4, d7::PigSeqW>(m, w, tail, row4, row5, pig_map::AccS4(), s);
    }
}

}  // namespace

// [[Rcpp::export]]
List pig1_dexpected3_cpp(NumericVector y, NumericVector mu, NumericVector sigma, int threads = 1) {
    const int n = (int) std::max(y.size(), std::max(mu.size(), sigma.size()));
    const bool one = mu.size() == 1 && sigma.size() == 1;
    const int nrun = one ? std::min(n, 1) : n;
    d34e::Par M(mu), X(sigma);
    List out = d34e::run(nrun, threads, d7::kMinCostly, 12,
                         [&](std::size_t i, d34e::Row o) {
        const double m = M[i], x = X[i];
        double c[12], s[15];
        bool ok = R_finite(m) && R_finite(x) && m > 0.0 && x > 0.0;
        if (ok) {
            ok = pig1_s_partials<3>(m, x, s);
            if (ok) pig_map::assemble3(m, x, s, c);
        }
        for (int k = 0; k < 12; ++k) o[k] = ok ? c[k] : NA_REAL;
    });
    if (nrun < n) {
        for (int k = 0; k < 12; ++k) {
            NumericVector col = out[k];
            out[k] = NumericVector(n, col[0]);
        }
    }
    CharacterVector nms(12);
    const char* nm[12] = {
        "mu_mu_mu_mu_mu", "mu_mu_mu_mu_sigma", "mu_mu_mu_sigma_sigma", "mu_mu_sigma_sigma_sigma",
        "sigma_sigma_mu_mu_mu", "sigma_sigma_mu_mu_sigma", "sigma_sigma_mu_sigma_sigma", "sigma_sigma_sigma_sigma_sigma",
        "mu_sigma_mu_mu_mu", "mu_sigma_mu_mu_sigma", "mu_sigma_mu_sigma_sigma", "mu_sigma_sigma_sigma_sigma",
    };
    for (int k = 0; k < 12; ++k) nms[k] = nm[k];
    out.names() = nms;
    return out;
}

