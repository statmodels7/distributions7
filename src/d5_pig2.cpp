#include <Rcpp.h>
#include "d7_par.h"
#include "pt_pig_d5.h"
#include "pt_pig_rows.h"
using namespace Rcpp;
using d7pigrow::pig2_d5_row;

// The fifth-order partials of the pig2 log-mass in (mu, alpha), written out.
//
// With r = sqrt(mu^2 + alpha^2), sigma = (mu + r)/alpha^2 and w = 1/(2 alpha),
//
//   l = y log mu - y log(alpha sigma) + 1/sigma - alpha + Lam(w),
//
// where -y log(alpha sigma) = -y log(mu + r) + y log alpha and
// 1/sigma - alpha = -mu alpha (1 + mu/(alpha + r))/(mu + r) (no cancellation).
// The derivatives of Lam in w, L1..L5, come from pig5_logS_w(); the partials
// of the elementary part and the chain through w are generated by sympy from
// D_v E = dE/dv + dE/dr dr/dv + sum_k dE/dL_k L_{k+1} dw/dv (the script and its
// 60-digit check are in misure_gas_congiunto/c/fase4/D5/pig2), reduced by cse.

// One row: the six fifth-order partials in mu and alpha. A missing response
// propagates; a response with no mass reads NaN, there being no derivative.
// pig2_d5_row() is in pt_pig_rows.h, shared with the third and fourth
// derivatives of the expected information (src/d34e_pig*.cpp).

// [[Rcpp::export]]
List pig2_deriv5_cpp(NumericVector y, NumericVector mu,
                     NumericVector alpha, int threads = 1) {
    int n = y.size();
    NumericVector o0(n), o1(n), o2(n), o3(n), o4(n), o5(n);
    double *d0 = o0.begin(), *d1 = o1.begin(), *d2 = o2.begin(),
        *d3 = o3.begin(), *d4 = o4.begin(), *d5 = o5.begin();
    bool mu_scalar = (mu.size() == 1), p2_scalar = (alpha.size() == 1);
    const double *yp = y.begin(), *mp = mu.begin(), *pp = alpha.begin();
    // the scalar branch is read INSIDE the loop, never hoisted into a
    // variable the workers write (d7_par.h)
    d7::par_for(n, threads, d7::kMinCostly, [&](std::size_t i) {
        double v[6];
        pig2_d5_row(yp[i], mu_scalar ? mp[0] : mp[i],
                    p2_scalar ? pp[0] : pp[i], v);
        d0[i] = v[0];
        d1[i] = v[1];
        d2[i] = v[2];
        d3[i] = v[3];
        d4[i] = v[4];
        d5[i] = v[5];
    });
    return List::create(
        Named("mu_mu_mu_mu_mu") = o0,
        Named("mu_mu_mu_mu_alpha") = o1,
        Named("mu_mu_mu_alpha_alpha") = o2,
        Named("mu_mu_alpha_alpha_alpha") = o3,
        Named("mu_alpha_alpha_alpha_alpha") = o4,
        Named("alpha_alpha_alpha_alpha_alpha") = o5
    );
}
